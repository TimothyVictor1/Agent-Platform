"""Export JSON Schema for every public contract (SPEC §5.1 decision 6).

Writes ``frontend/src/contracts/schema.json``; ``frontend/scripts/gen-contracts.mjs``
turns it into ``frontend/src/contracts/generated.ts``. Run both with ``make contracts``.

Usage (from backend/): ``uv run python ../scripts/gen_contracts.py [--out PATH]``

Conventions of the exported schema:

* Everything is in ``$defs`` keyed by class name; the root lists nothing (the TS
  generator emits all definitions).
* Response/domain models use pydantic's *serialization* schema, so fields with
  defaults are required (the API always sends them).
* Top-level ``*Request`` models only require fields without defaults, so the
  frontend may omit optional request fields.
* Property-level ``title``s are dropped so the TS generator does not create a type
  alias per property.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel, TypeAdapter
from pydantic.json_schema import models_json_schema

from agentplatform.contracts import PUBLIC_MODELS
from agentplatform.contracts.api import WsServerMessage
from agentplatform.contracts.commands import Command
from agentplatform.contracts.events import EphemeralMessage, Event

REF_TEMPLATE = "#/$defs/{model}"
ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "frontend" / "src" / "contracts" / "schema.json"

UNIONS: dict[str, Any] = {
    "Event": Event,
    "Command": Command,
    "WsServerMessage": WsServerMessage,
    "EphemeralMessage": EphemeralMessage,
}


def _strip_property_titles(node: Any) -> None:
    if isinstance(node, dict):
        props = node.get("properties")
        if isinstance(props, dict):
            for prop in props.values():
                if isinstance(prop, dict):
                    prop.pop("title", None)
        for value in node.values():
            _strip_property_titles(value)
    elif isinstance(node, list):
        for item in node:
            _strip_property_titles(item)


def _relax_request(schema: dict[str, Any], model: type[BaseModel]) -> None:
    required = [name for name, field in model.model_fields.items() if field.is_required()]
    if required:
        schema["required"] = required
    else:
        schema.pop("required", None)


def build_schema() -> dict[str, Any]:
    models = sorted(set(PUBLIC_MODELS), key=lambda m: m.__name__)
    names = [m.__name__ for m in models]
    duplicates = {n for n in names if names.count(n) > 1}
    if duplicates:
        raise SystemExit(f"duplicate public model names: {sorted(duplicates)}")

    _, top = models_json_schema(
        [(m, "serialization") for m in models], ref_template=REF_TEMPLATE
    )
    defs: dict[str, Any] = dict(top.get("$defs", {}))

    for name, union in UNIONS.items():
        schema = TypeAdapter(union).json_schema(mode="serialization", ref_template=REF_TEMPLATE)
        defs.update(schema.pop("$defs", {}))
        schema["title"] = name
        defs[name] = schema

    for model in models:
        if model.__name__.endswith("Request"):
            _relax_request(defs[model.__name__], model)

    _strip_property_titles(defs)
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "AgentPlatformContracts",
        "description": "Generated by scripts/gen_contracts.py. Do not edit.",
        "type": "object",
        "additionalProperties": False,
        "$defs": dict(sorted(defs.items())),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(build_schema(), indent=2, sort_keys=False) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
